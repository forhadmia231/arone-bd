function id(prefix = 'blk') {
  return `${prefix}_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;
}

function block(type, values = {}) {
  return {
    id: id(),
    type,
    backgroundColor: palette.white,
    textColor: palette.ink,
    paddingTop: 58,
    paddingBottom: 58,
    ...values,
  };
}

